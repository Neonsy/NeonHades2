import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { collectUsedPhosphorIcons } from './phosphor-subset.mjs';

const packageDirectory = path.resolve('node_modules/@phosphor-icons/web/src/regular');
const packageStylesheet = path.join(packageDirectory, 'style.css');
const packageFont = path.join(packageDirectory, 'Phosphor.ttf');
const outputFont = path.resolve('public/fonts/phosphor-regular-subset.woff2');
const outputStylesheet = path.resolve('src/styles/phosphor-subset.css');
const outputManifest = path.resolve('scripts/phosphor-subset.generated.json');

const upstreamCss = await readFile(packageStylesheet, 'utf8');
const glyphs = new Map(
    [...upstreamCss.matchAll(/\.ph\.(ph-[a-z0-9-]+):before\s*\{\s*content:\s*"\\([a-f0-9]+)";\s*\}/gu)].map(
        ([, name, codepoint]) => [name, codepoint]
    )
);
const icons = await collectUsedPhosphorIcons();
const missing = icons.filter((name) => !glyphs.has(name));
if (missing.length > 0) throw new Error(`Unknown Phosphor icon classes: ${missing.join(', ')}`);

const codepoints = icons.map((name) => `U+${glyphs.get(name).toUpperCase()}`).join(',');
await mkdir(path.dirname(outputFont), { recursive: true });
const subset = spawnSync(
    process.platform === 'win32' ? 'uvx.exe' : 'uvx',
    [
        '--from',
        'fonttools',
        '--with',
        'brotli',
        'pyftsubset',
        packageFont,
        `--unicodes=${codepoints}`,
        '--flavor=woff2',
        '--no-hinting',
        `--output-file=${outputFont}`,
    ],
    { encoding: 'utf8' }
);
if (subset.status !== 0) throw new Error(subset.stderr || subset.stdout || 'Phosphor font subsetting failed.');

const iconRules = icons.map((name) => `.ph.${name}:before {\n    content: "\\${glyphs.get(name)}";\n}`).join('\n');
const generatedCss = `/* Generated by scripts/generate-phosphor-subset.mjs. */
@font-face {
    font-family: 'Phosphor';
    src: url('/fonts/phosphor-regular-subset.woff2') format('woff2');
    font-style: normal;
    font-weight: normal;
    font-display: swap;
}

.ph {
    font-family: 'Phosphor' !important;
    speak: never;
    font-style: normal;
    font-weight: normal;
    font-variant: normal;
    text-transform: none;
    line-height: 1;
    letter-spacing: 0;
    font-feature-settings: 'liga';
    font-variant-ligatures: discretionary-ligatures;
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
}

${iconRules}
`;

await writeFile(outputStylesheet, generatedCss);
await writeFile(outputManifest, `${JSON.stringify({ icons }, null, 4)}\n`);
console.warn(`Generated ${icons.length}-glyph Phosphor subset.`);
