export const hasPortraitPlan = (name) => Boolean(profiles[name] || specialPortraits[name]);

export const portraitFromPlan = (name) => {
    if (specialPortraits[name]) return specialPortraits[name];
    const profile = profiles[name];
    if (!profile) throw new Error(`No explicit portrait plan for ${name}.`);
    return `${body(profile)}${prop(profile)}${face(profile)}${hair(profile)}`;
};

